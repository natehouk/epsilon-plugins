#!/usr/bin/env python3
"""Windows: an Inno Setup installer with a component per plugin and, under it, per format.

    python3 installers/build-windows.py <suite version>     (after fetch.py windows-x64)

Writes build/windows-x64/suite.iss and, when Inno Setup's ISCC.exe is found (Windows), compiles it to
build/out/Epsilon-Audio-Suite-<version>-windows-x64.exe. VST3 and CLAP are selected by default, VST2 is
available under the "Full" type or by ticking it. Install locations are the standard shared folders:
  VST3  C:\\Program Files\\Common Files\\VST3      CLAP  C:\\Program Files\\Common Files\\CLAP
  VST2  C:\\Program Files\\Steinberg\\VSTPlugins    Manuals  C:\\Program Files\\Epsilon Audio\\Manuals
The installer is unsigned until a code-signing certificate is added (Windows SmartScreen will warn).
"""
import json, os, shutil, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
version = sys.argv[1]
build = os.path.join(here, "build", "windows-x64")
stage = os.path.join(build, "stage")
outdir = os.path.join(here, "build", "out"); os.makedirs(outdir, exist_ok=True)
catalog = [p["name"] for p in json.load(open(os.path.join(here, "..", "plugins.json")))["plugins"]]
summaries = {p["name"]: p.get("subtitle", "") for p in json.load(open(os.path.join(here, "..", "plugins.json")))["plugins"]}
versions = {v["name"]: v["tag"] for v in json.load(open(os.path.join(build, "versions.json")))}
names = [n for n in catalog if os.path.isdir(os.path.join(stage, n))]

def q(s): return s.replace('"', "'")

comps, files = [], []
for n in names:
    k = n.lower(); src = os.path.join(stage, n)
    comps.append(f'Name: "{k}"; Description: "{q(n)} {versions.get(n, "").lstrip("v")}, {q(summaries.get(n, "")).lower()}"; Types: full recommended custom')
    if os.path.isdir(os.path.join(src, n + ".vst3")):
        comps.append(f'Name: "{k}\\vst3"; Description: "VST3"; Types: full recommended custom')
        files.append(f'Source: "{src}\\{n}.vst3\\*"; DestDir: "{{commoncf64}}\\VST3\\{n}.vst3"; Components: {k}\\vst3; Flags: ignoreversion recursesubdirs createallsubdirs')
    if os.path.exists(os.path.join(src, n + ".clap")):
        comps.append(f'Name: "{k}\\clap"; Description: "CLAP"; Types: full recommended custom')
        files.append(f'Source: "{src}\\{n}.clap"; DestDir: "{{commoncf64}}\\CLAP"; Components: {k}\\clap; Flags: ignoreversion')
    if os.path.exists(os.path.join(src, n + "-vst.dll")):
        comps.append(f'Name: "{k}\\vst2"; Description: "VST2 (older hosts)"; Types: full')
        files.append(f'Source: "{src}\\{n}-vst.dll"; DestDir: "{{commonpf64}}\\Steinberg\\VSTPlugins"; DestName: "{n}.dll"; Components: {k}\\vst2; Flags: ignoreversion')
    if os.path.exists(os.path.join(src, n + "-Manual.html")):
        files.append(f'Source: "{src}\\{n}-Manual.html"; DestDir: "{{app}}\\Manuals"; Components: {k}; Flags: ignoreversion')

license_path = os.path.abspath(os.path.join(here, "..", "LICENSE"))
iss = f"""; Generated by installers/build-windows.py; do not edit by hand.
[Setup]
AppId={{{{6E1F4C2A-5B7D-4C1E-9A3F-E95110A0D10E}}
AppName=Epsilon Audio Suite
AppVersion={version}
AppVerName=Epsilon Audio Suite {version}
AppPublisher=Epsilon Records
AppPublisherURL=https://plugins.epsilonrecords.com
AppSupportURL=https://plugins.epsilonrecords.com/install
DefaultDirName={{commonpf64}}\\Epsilon Audio
DisableDirPage=yes
DefaultGroupName=Epsilon Audio
DisableProgramGroupPage=yes
LicenseFile={license_path}
OutputDir={outdir}
OutputBaseFilename=Epsilon-Audio-Suite-{version}-windows-x64
Compression=lzma2/max
SolidCompression=yes
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible
PrivilegesRequired=admin
WizardStyle=modern
UninstallDisplayName=Epsilon Audio Suite

[Types]
Name: "recommended"; Description: "VST3 and CLAP (recommended)"
Name: "full"; Description: "Everything, including VST2"
Name: "custom"; Description: "Choose plugins and formats"; Flags: iscustom

[Components]
{chr(10).join(comps)}

[Files]
{chr(10).join(files)}

[Icons]
Name: "{{group}}\\Epsilon Audio manuals"; Filename: "{{app}}\\Manuals"
Name: "{{group}}\\Install guides"; Filename: "https://plugins.epsilonrecords.com/install"
Name: "{{group}}\\Uninstall Epsilon Audio Suite"; Filename: "{{uninstallexe}}"

[Messages]
FinishedLabel=The plugins are installed. Rescan plugins in your DAW to find them under Epsilon Audio.
"""
iss_path = os.path.join(build, "suite.iss")
open(iss_path, "w", encoding="utf-8").write(iss)
print(iss_path)
iscc = shutil.which("iscc") or next((p for p in [r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe", r"C:\Program Files\Inno Setup 6\ISCC.exe"] if os.path.exists(p)), None)
if not iscc:
    print("ISCC.exe not found: wrote the script only"); sys.exit(0 if os.name != "nt" else 1)
subprocess.run([iscc, iss_path], check=True)
print(os.path.join(outdir, f"Epsilon-Audio-Suite-{version}-windows-x64.exe"))
